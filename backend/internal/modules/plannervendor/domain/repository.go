package domain

import (
	"context"
	"errors"

	"github.com/google/uuid"

	pd "github.com/aliyyulmanbinus/adicara-platform/backend/internal/modules/planner/domain"
)

// ErrNotFound, ErrInvalidScope and ErrConflict are the sentinels of the planner module (the shared TxManager already
// returns pd.ErrConflict for a failed COMMIT); they are reused so one mapping serves every planner module.
var (
	ErrNotFound     = pd.ErrNotFound
	ErrInvalidScope = pd.ErrInvalidScope
	ErrConflict     = pd.ErrConflict

	// ErrInvalidVendor: an item pointed at a vendor of another project (the composite foreign key).
	ErrInvalidVendor = errors.New("vendor does not belong to the project")
	// ErrInvalidBudgetItem: an item pointed at a budget line of another project (the composite foreign key).
	ErrInvalidBudgetItem = errors.New("budget line does not belong to the project")
)

// SessionRef is the part of a session the export and the scope check need.
type SessionRef struct {
	ScopeKey string
	Name     string
}

// BudgetLineRef is the part of a planner_budget_items row that lock-deal decides on.
type BudgetLineRef struct {
	ID   uuid.UUID
	Unit bool // pricing_mode = 'unit': its estimate is quantity × unit price and is never replaced by a deal
}

// BudgetItemRef is a budget line as the rollup needs it; Estimate and Paid are the effective figures of the view.
type BudgetItemRef struct {
	ID                      uuid.UUID
	SubEventScope, ItemKey  string
	ItemName                string
	Unit, Rollup            bool
	VendorLinked, DocLinked bool
	HasPayments             bool // dp + term 1 + term 2 stored > 0
	Estimate, Paid          int64
}

// NewBudgetLine is a line made by lock-deal or by the rollup. Its payments are all 0.
type NewBudgetLine struct {
	SubEventScope string
	Category      string
	ItemName      string
	ItemKey       *string
	Source        string // vendor | manual
	VendorID      *uuid.UUID
	Estimate      int64
}

// ShoppingWrite is the writable part of a planner_shopping_items row. The totals and price_delta are generated by the database.
type ShoppingWrite struct {
	ID               uuid.UUID
	SubEventScope    string
	Category         string
	ItemName         string
	QuantityX100     int64
	Unit             *string
	EstimatedPrice   int64
	ActualPrice      int64
	PurchaseLocation *string
	VendorID         *uuid.UUID
	BudgetItemID     *uuid.UUID
	Purpose          *string
	Status           string
	Notes            *string
	TemplateKey      *string
}

// TemplateImpact describes the template items that replace_template would delete.
type TemplateImpact struct {
	Removed     int
	CarryWork   int // items that hold work of the user: a status other than belum, an actual price, a link or the souvenir mark
	RollupLinks int // items linked to a rollup line
}

// Repository is the PostgreSQL side of the module. Every method that takes a projectID filters by it; ids that come
// from a URL are always looked up with both (WHERE id = $x AND project_id = $y).
type Repository interface {
	// LockProject takes SELECT … FOR UPDATE on the project row. Needs a transaction.
	LockProject(ctx context.Context, projectID uuid.UUID) error
	Sessions(ctx context.Context, projectID uuid.UUID) ([]SessionRef, error)

	// ---------- vendors ----------
	// ListVendors returns every vendor in display order (sort_order, then creation).
	ListVendors(ctx context.Context, projectID uuid.UUID) ([]VendorRow, error)
	VendorByID(ctx context.Context, projectID, id uuid.UUID) (VendorRow, error)
	CountVendors(ctx context.Context, projectID uuid.UUID) (int, error)
	// InsertVendor appends the vendor (sort_order = max + 1); v.SortOrder is filled.
	InsertVendor(ctx context.Context, projectID uuid.UUID, v *VendorRow) error
	// UpdateVendor writes session, category, name, contact, portfolio, limit, price, status and notes (never the order).
	UpdateVendor(ctx context.Context, projectID uuid.UUID, v *VendorRow) error
	SetVendorStatus(ctx context.Context, projectID, id uuid.UUID, status VendorStatus) error
	// SetVendorDeal makes the vendor fix with the agreed price (step 1 of lock-deal).
	SetVendorDeal(ctx context.Context, projectID, id uuid.UUID, price int64) error
	DeleteVendor(ctx context.Context, projectID, id uuid.UUID) error
	// ActiveScenarioRows are the lines of the active scenario that take part in the simulation (04 BE 2.1).
	ActiveScenarioRows(ctx context.Context, projectID uuid.UUID) ([]ScenarioRow, error)
	// Lines are the rows of planner_budget_lines that have an item_key or point at a vendor.
	Lines(ctx context.Context, projectID uuid.UUID) ([]LineRow, error)

	// ---------- lock-deal (04 BE 2.2) ----------
	// VendorLine is the line that points at the vendor (step 2a).
	VendorLine(ctx context.Context, projectID, vendorID uuid.UUID) (BudgetLineRef, bool, error)
	// FreeLine is the dedicated line of the category that no vendor and no rollup holds yet: item_key in keys, session
	// scope first and then 'all' (step 2c).
	FreeLine(ctx context.Context, projectID uuid.UUID, keys []string, scope string) (BudgetLineRef, bool, error)
	// LinkVendorToLine sets vendor_id (and the estimate, unless the line is unit-priced) when no vendor holds the line;
	// linked is false when another request got there first.
	LinkVendorToLine(ctx context.Context, projectID, lineID, vendorID uuid.UUID, price int64) (linked bool, err error)
	// RepriceVendorLines sets the estimate of the line of the vendor, unless it is unit-priced.
	RepriceVendorLines(ctx context.Context, projectID, vendorID uuid.UUID, price int64) error
	// CountBudgetLines counts the budget lines of the project (the limit of menu 03 applies to the lines made here too).
	CountBudgetLines(ctx context.Context, projectID uuid.UUID) (int, error)
	InsertBudgetLine(ctx context.Context, projectID uuid.UUID, l NewBudgetLine) (uuid.UUID, error)
	// ReleaseVendorLines clears vendor_id of the lines of the vendor and returns how many it cleared.
	ReleaseVendorLines(ctx context.Context, projectID, vendorID uuid.UUID) (int, error)

	// ---------- shopping ----------
	VendorInProject(ctx context.Context, projectID, vendorID uuid.UUID) (bool, error)
	ListShopping(ctx context.Context, projectID uuid.UUID) ([]ShoppingItem, error)
	ShoppingByID(ctx context.Context, projectID, id uuid.UUID) (ShoppingItem, error)
	CountShopping(ctx context.Context, projectID uuid.UUID) (int, error)
	// InsertShopping appends the item (sort_order = max + 1).
	InsertShopping(ctx context.Context, projectID uuid.UUID, it *ShoppingWrite) error
	// UpdateShopping writes everything but the rollup link, the template key and the order.
	UpdateShopping(ctx context.Context, projectID uuid.UUID, it *ShoppingWrite) error
	// SetShoppingStatus sets the status; finishing an item without an actual price copies the estimate into it.
	SetShoppingStatus(ctx context.Context, projectID, id uuid.UUID, status string) error
	DeleteShopping(ctx context.Context, projectID, id uuid.UUID) error
	// CountShoppingIDs returns how many of ids are items of the project.
	CountShoppingIDs(ctx context.Context, projectID uuid.UUID, ids []uuid.UUID) (int, error)

	// ---------- rollup (04 BE 2.4) ----------
	RollupLines(ctx context.Context, projectID uuid.UUID) ([]RollupLine, error)
	// BudgetItem reads a line with its effective figures; ErrNotFound for a line of another project.
	BudgetItem(ctx context.Context, projectID, id uuid.UUID) (BudgetItemRef, error)
	// BudgetItemByKey is the line with that item_key in any session (lowest sort_order); found is false when there is none.
	BudgetItemByKey(ctx context.Context, projectID uuid.UUID, key string) (BudgetItemRef, bool, error)
	SetRollup(ctx context.Context, projectID, lineID uuid.UUID, on bool) error
	// LinkShoppingItems points items at the line: ids, or every item when ids is nil. Items already linked to
	// another line stay. It returns how many items were linked now.
	LinkShoppingItems(ctx context.Context, projectID, lineID uuid.UUID, ids []uuid.UUID) (int, error)
	// UnlinkShoppingItems clears budget_item_id of every item that points at the line.
	UnlinkShoppingItems(ctx context.Context, projectID, lineID uuid.UUID) (int, error)

	// ---------- template ----------
	TemplateImpact(ctx context.Context, projectID uuid.UUID) (TemplateImpact, error)
	// InsertTemplateItem inserts unless the template_key exists in the project; the item gets sort_order = max + 1.
	InsertTemplateItem(ctx context.Context, projectID uuid.UUID, it *ShoppingWrite) (inserted bool, err error)
	DeleteTemplateItems(ctx context.Context, projectID uuid.UUID) (int, error)

	// ---------- sample dataset ----------
	// LinkLineByKey sets vendor_id on the line (scope, key) without touching its estimate; ErrNotFound when there is no such line.
	LinkLineByKey(ctx context.Context, projectID uuid.UUID, scope, key string, vendorID uuid.UUID) error
	// LinkTaskByTemplateKey sets vendor_id on the task with that template_key; ErrNotFound when there is none.
	LinkTaskByTemplateKey(ctx context.Context, projectID uuid.UUID, templateKey string, vendorID uuid.UUID) error
	// SetSampleShopping sets the status and the actual price of the template item.
	SetSampleShopping(ctx context.Context, projectID uuid.UUID, templateKey, status string, actualPrice int64) error
}
